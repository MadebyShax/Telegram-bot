"""
Regenerates src/data/pythonCodebase.ts from the real bot source files,
so the web preview (Codebase Explorer + ZIP export) never shows outdated code.

Run from the repository root after changing any bot file:
    python scripts/generate_codebase_ts.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src" / "data" / "pythonCodebase.ts"

# (path, category, description) — order is the order shown in the Codebase Explorer
FILES = [
    ("app.py", "deploy", "Hugging Face Spaces entrypoint: health-check server on port 7860 + Telegram polling."),
    ("bot/main.py", "bot", "Bot setup shared by app.py: dependency injection middleware (DB session, services, user language) and polling."),
    ("bot/i18n.py", "bot", "All user-facing bot texts in Uzbek, Russian and English."),
    ("bot/handlers/__init__.py", "bot", "Combines all routers."),
    ("bot/handlers/start.py", "bot", "/start, phone verification bonus, language selection and help."),
    ("bot/handlers/upload.py", "bot", "Zero-prompt flow: photo upload, atomic credit reservation, 5 studio cards, SEO copy."),
    ("bot/handlers/payment.py", "bot", "Click / Payme top-up buttons, invoices and successful payment handling."),
    ("services/google_ai_studio_service.py", "services", "Gemini product analysis + Gemini image model that re-shoots the user's own product in 5 studio scenes."),
    ("services/payment_service.py", "services", "Telegram native payments: invoices, pre-checkout validation, idempotent crediting."),
    ("database/db.py", "database", "Async SQLAlchemy engine, session factory and schema initialization."),
    ("database/models.py", "database", "User, Transaction and CardGeneration models."),
    ("config.py", "config", "Settings loaded from environment variables / .env."),
    ("requirements.txt", "config", "Python dependencies."),
    (".env.example", "config", "Example environment variables."),
    ("Dockerfile", "deploy", "Hugging Face Spaces compatible Docker image."),
    ("docker-compose.yml", "deploy", "Local run with PostgreSQL."),
    ("README.md", "deploy", "Hugging Face Spaces deployment guide."),
]

LANGUAGES = {".py": "python", ".txt": "text", ".yml": "yaml", ".md": "markdown", ".example": "bash"}

HEADER = """// AUTO-GENERATED by scripts/generate_codebase_ts.py — do not edit by hand.
// Run `python scripts/generate_codebase_ts.py` after changing the bot source files.

export interface CodeFile {
  path: string;
  name: string;
  language: string;
  category: 'bot' | 'services' | 'database' | 'config' | 'deploy';
  description: string;
  content: string;
}

export const PYTHON_CODEBASE_FILES: CodeFile[] = [
"""


def language_for(path: pathlib.PurePosixPath) -> str:
    if path.name == "Dockerfile":
        return "dockerfile"
    return LANGUAGES.get(path.suffix, "text")


def main():
    entries = []
    for rel_path, category, description in FILES:
        source = ROOT / rel_path
        path = pathlib.PurePosixPath(rel_path)
        content = source.read_text(encoding="utf-8").replace("\r\n", "\n")
        # json.dumps produces a valid TypeScript string literal (escapes quotes, backslashes, newlines)
        entries.append(
            "  {\n"
            f"    path: {json.dumps(rel_path)},\n"
            f"    name: {json.dumps(path.name)},\n"
            f"    language: {json.dumps(language_for(path))},\n"
            f"    category: {json.dumps(category)},\n"
            f"    description: {json.dumps(description, ensure_ascii=False)},\n"
            f"    content: {json.dumps(content, ensure_ascii=False)},\n"
            "  }"
        )

    OUTPUT.write_text(HEADER + ",\n".join(entries) + "\n];\n", encoding="utf-8", newline="\n")
    print(f"Wrote {len(entries)} files to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
